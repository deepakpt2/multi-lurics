//! Image storage and processing. The store is a trait so local disk can later be swapped for an
//! S3-compatible bucket without touching the use cases. Processing never trusts the upload: the
//! content decides the type, pixels are decoded and re-encoded (which drops EXIF, GPS and any
//! embedded payload), and sizes are fixed by configuration.

use async_trait::async_trait;
use image::imageops::FilterType;
use image::{DynamicImage, ImageDecoder, ImageFormat, ImageReader, Limits, RgbImage};
use std::io::Cursor;
use std::path::{Path, PathBuf};
use uuid::Uuid;

/// Smallest accepted side: below this a "photo" is an icon and looks broken when enlarged.
pub const MIN_SIDE: u32 = 64;
const JPEG_QUALITY: u8 = 85;

#[async_trait]
pub trait MediaStore: Send + Sync {
    async fn put(&self, key: &str, bytes: Vec<u8>) -> std::io::Result<()>;
    async fn get(&self, key: &str) -> std::io::Result<Option<Vec<u8>>>;
    /// Removes every object under `prefix` (an image's directory). Missing is not an error.
    async fn delete_prefix(&self, prefix: &str) -> std::io::Result<()>;
}

pub fn key(image: Uuid, size: u32) -> String {
    format!("{image}/{size}.jpg")
}

pub struct LocalStore {
    root: PathBuf,
}

impl LocalStore {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    /// Keys are generated by the server (`<uuid>/<size>.jpg`); anything else is refused outright.
    fn path(&self, key: &str) -> std::io::Result<PathBuf> {
        let ok = key.split('/').all(|p| {
            !p.is_empty()
                && p != "."
                && p != ".."
                && p.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'.')
        });
        if ok {
            Ok(self.root.join(key))
        } else {
            Err(std::io::Error::new(
                std::io::ErrorKind::InvalidInput,
                "invalid media key",
            ))
        }
    }
}

#[async_trait]
impl MediaStore for LocalStore {
    async fn put(&self, key: &str, bytes: Vec<u8>) -> std::io::Result<()> {
        let path = self.path(key)?;
        if let Some(dir) = path.parent() {
            tokio::fs::create_dir_all(dir).await?;
        }
        // Write then rename, so a reader never sees half a file.
        let tmp = path.with_extension(format!("tmp{}", Uuid::new_v4().simple()));
        tokio::fs::write(&tmp, bytes).await?;
        tokio::fs::rename(&tmp, &path).await
    }

    async fn get(&self, key: &str) -> std::io::Result<Option<Vec<u8>>> {
        match tokio::fs::read(self.path(key)?).await {
            Ok(b) => Ok(Some(b)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e),
        }
    }

    async fn delete_prefix(&self, prefix: &str) -> std::io::Result<()> {
        let dir: &Path = &self.path(prefix)?;
        match tokio::fs::remove_dir_all(dir).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(e),
        }
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum MediaError {
    /// Not a JPEG, PNG, WebP or GIF (decided from the content, not the file name).
    UnsupportedType,
    /// Could not be decoded, or exceeds the decoder's memory limit.
    Corrupt,
    /// Wider or taller than the configured maximum.
    TooLarge,
    /// Smaller than `MIN_SIDE` on a side.
    TooSmall,
}

pub struct Processed {
    pub width: u32,
    pub height: u32,
    /// `(size, jpeg bytes)`, ascending. Each is a centred square crop; sizes the source cannot fill are skipped.
    pub variants: Vec<(u32, Vec<u8>)>,
}

pub fn process(bytes: &[u8], sizes: &[u32], max_side: u32) -> Result<Processed, MediaError> {
    let format = image::guess_format(bytes).map_err(|_| MediaError::UnsupportedType)?;
    if !matches!(
        format,
        ImageFormat::Jpeg | ImageFormat::Png | ImageFormat::WebP | ImageFormat::Gif
    ) {
        return Err(MediaError::UnsupportedType);
    }
    let mut reader = ImageReader::with_format(Cursor::new(bytes), format);
    let mut limits = Limits::default();
    limits.max_image_width = Some(max_side);
    limits.max_image_height = Some(max_side);
    limits.max_alloc = Some(512 * 1024 * 1024);
    reader.limits(limits);
    let mut decoder = reader.into_decoder().map_err(|e| classify(&e))?;
    let (w, h) = decoder.dimensions();
    if w > max_side || h > max_side {
        return Err(MediaError::TooLarge);
    }
    if w < MIN_SIDE || h < MIN_SIDE {
        return Err(MediaError::TooSmall);
    }
    let orientation = decoder.orientation().ok();
    let mut img = DynamicImage::from_decoder(decoder).map_err(|e| classify(&e))?;
    if let Some(o) = orientation {
        img.apply_orientation(o);
    }
    let rgb = flatten(&img);
    let (width, height) = (rgb.width(), rgb.height());
    let smallest_side = width.min(height);

    let mut variants: Vec<(u32, Vec<u8>)> = Vec::new();
    for &size in sizes {
        // Never enlarge: the biggest variant is capped at what the source can supply.
        let size = size.min(smallest_side);
        if variants.iter().any(|(s, _)| *s == size) {
            continue;
        }
        let square = DynamicImage::ImageRgb8(rgb.clone()).resize_to_fill(size, size, FilterType::Lanczos3);
        let mut out = Vec::new();
        image::codecs::jpeg::JpegEncoder::new_with_quality(&mut out, JPEG_QUALITY)
            .encode_image(&square.to_rgb8())
            .map_err(|_| MediaError::Corrupt)?;
        variants.push((size, out));
    }
    Ok(Processed {
        width,
        height,
        variants,
    })
}

pub struct ProcessedWide {
    pub width: u32,
    pub height: u32,
    /// `(width, jpeg bytes)`, ascending; proportions kept, never enlarged.
    pub variants: Vec<(u32, Vec<u8>)>,
}

/// For article pictures: like `process`, but keeps the picture's proportions.
pub fn process_wide(bytes: &[u8], widths: &[u32], max_side: u32) -> Result<ProcessedWide, MediaError> {
    let format = image::guess_format(bytes).map_err(|_| MediaError::UnsupportedType)?;
    if !matches!(
        format,
        ImageFormat::Jpeg | ImageFormat::Png | ImageFormat::WebP | ImageFormat::Gif
    ) {
        return Err(MediaError::UnsupportedType);
    }
    let mut reader = ImageReader::with_format(Cursor::new(bytes), format);
    let mut limits = Limits::default();
    limits.max_image_width = Some(max_side);
    limits.max_image_height = Some(max_side);
    limits.max_alloc = Some(512 * 1024 * 1024);
    reader.limits(limits);
    let mut decoder = reader.into_decoder().map_err(|e| classify(&e))?;
    let (w, h) = decoder.dimensions();
    if w > max_side || h > max_side {
        return Err(MediaError::TooLarge);
    }
    if w < MIN_SIDE || h < MIN_SIDE {
        return Err(MediaError::TooSmall);
    }
    let orientation = decoder.orientation().ok();
    let mut img = DynamicImage::from_decoder(decoder).map_err(|e| classify(&e))?;
    if let Some(o) = orientation {
        img.apply_orientation(o);
    }
    let rgb = DynamicImage::ImageRgb8(flatten(&img));
    let (width, height) = (rgb.width(), rgb.height());
    let mut variants: Vec<(u32, Vec<u8>)> = Vec::new();
    for &target in widths {
        let target = target.min(width);
        if variants.iter().any(|(s, _)| *s == target) {
            continue;
        }
        let h = ((u64::from(height) * u64::from(target)) / u64::from(width)).max(1) as u32;
        let scaled = rgb.resize_exact(target, h, FilterType::Lanczos3);
        let mut out = Vec::new();
        image::codecs::jpeg::JpegEncoder::new_with_quality(&mut out, JPEG_QUALITY)
            .encode_image(&scaled.to_rgb8())
            .map_err(|_| MediaError::Corrupt)?;
        variants.push((target, out));
    }
    variants.sort_by_key(|v| v.0);
    Ok(ProcessedWide {
        width,
        height,
        variants,
    })
}

fn classify(e: &image::ImageError) -> MediaError {
    match e {
        image::ImageError::Limits(_) => MediaError::TooLarge,
        image::ImageError::Unsupported(_) => MediaError::UnsupportedType,
        _ => MediaError::Corrupt,
    }
}

/// Transparent pixels become white: JPEG has no alpha and black backgrounds look like damage.
fn flatten(img: &DynamicImage) -> RgbImage {
    if !img.color().has_alpha() {
        return img.to_rgb8();
    }
    let rgba = img.to_rgba8();
    let mut out = RgbImage::new(rgba.width(), rgba.height());
    for (x, y, p) in rgba.enumerate_pixels() {
        let a = u32::from(p[3]);
        let mix = |c: u8| ((u32::from(c) * a + 255 * (255 - a)) / 255) as u8;
        out.put_pixel(x, y, image::Rgb([mix(p[0]), mix(p[1]), mix(p[2])]));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn png(w: u32, h: u32) -> Vec<u8> {
        let img = DynamicImage::ImageRgb8(RgbImage::from_fn(w, h, |x, y| {
            image::Rgb([(x % 255) as u8, (y % 255) as u8, 90])
        }));
        let mut out = Cursor::new(Vec::new());
        img.write_to(&mut out, ImageFormat::Png).unwrap();
        out.into_inner()
    }

    #[test]
    fn makes_square_jpegs_and_never_enlarges() {
        let p = process(&png(200, 100), &[32, 64, 256], 4000).unwrap();
        assert_eq!((p.width, p.height), (200, 100));
        // 256 is capped at the shorter side (100).
        assert_eq!(p.variants.iter().map(|v| v.0).collect::<Vec<_>>(), vec![32, 64, 100]);
        for (size, bytes) in &p.variants {
            assert_eq!(image::guess_format(bytes).unwrap(), ImageFormat::Jpeg);
            let img = image::load_from_memory(bytes).unwrap();
            assert_eq!((img.width(), img.height()), (*size, *size));
        }
    }

    #[test]
    fn refuses_what_is_not_a_usable_image() {
        assert_eq!(
            process(b"<svg onload=alert(1)/>", &[32], 4000).err(),
            Some(MediaError::UnsupportedType)
        );
        assert_eq!(process(&png(30, 300), &[32], 4000).err(), Some(MediaError::TooSmall));
        assert_eq!(process(&png(500, 100), &[32], 400).err(), Some(MediaError::TooLarge));
        let mut broken = png(100, 100);
        broken.truncate(broken.len() / 2);
        assert_eq!(process(&broken, &[32], 4000).err(), Some(MediaError::Corrupt));
    }

    #[tokio::test]
    async fn local_store_round_trips_and_refuses_traversal() {
        let dir = std::env::temp_dir().join(format!("media-test-{}", Uuid::new_v4()));
        let s = LocalStore::new(&dir);
        let id = Uuid::new_v4();
        s.put(&key(id, 64), vec![1, 2, 3]).await.unwrap();
        assert_eq!(s.get(&key(id, 64)).await.unwrap(), Some(vec![1, 2, 3]));
        assert_eq!(s.get(&key(id, 96)).await.unwrap(), None);
        assert!(s.get("../etc/passwd").await.is_err());
        assert!(s.put("/abs/x.jpg", vec![]).await.is_err());
        s.delete_prefix(&id.to_string()).await.unwrap();
        assert_eq!(s.get(&key(id, 64)).await.unwrap(), None);
        s.delete_prefix(&id.to_string()).await.unwrap();
        let _ = std::fs::remove_dir_all(dir);
    }
}
